#!/bin/sh
# Blocks edits to generated output, dependency lockfiles and (during a fix task) test files.
set -eu
path=$(sed -n 's/.*"file_path"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)
[ -n "$path" ] || exit 0
rel=${path#"${CLAUDE_PROJECT_DIR:-}"/}
block() { echo "$1" >&2; exit 2; }
case "$rel" in
  internal/web/dist/*) block "internal/web/dist is generated by 'make web'; edit web/src instead." ;;
  brand/png/*|brand/icons/png/*) block "Rendered brand PNGs come from brand/tools; regenerate rather than edit." ;;
  go.sum|web/package-lock.json) [ "${PM_ALLOW_DEPS:-}" = 1 ] || block "Dependency lockfiles change only in an upgrade task (set PM_ALLOW_DEPS=1)." ;;
esac
if [ "${PM_FIX_TASK:-}" = 1 ]; then
  case "$rel" in
    *_test.go|*.test.ts|*.test.tsx|*.spec.ts|testdata/*) block "Fix task: the failing test is the proof and may not change (PM_FIX_TASK=1)." ;;
  esac
fi
exit 0
