-- firmware area tables (PostgreSQL; mirrors schema_firmware.sql).

CREATE TABLE IF NOT EXISTS firmware_packages (
  id TEXT PRIMARY KEY,
  vendor TEXT NOT NULL DEFAULT '',
  models JSONB NOT NULL DEFAULT '[]',
  version TEXT NOT NULL,
  min_version TEXT NOT NULL DEFAULT '',
  file_name TEXT NOT NULL,
  size BIGINT NOT NULL DEFAULT 0,
  sha256 TEXT NOT NULL,
  storage_path TEXT NOT NULL,
  notes TEXT NOT NULL DEFAULT '',
  created_by TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL
);

-- package_id is not a foreign key on purpose (see schema_firmware.sql).
-- "window" is a reserved word in PostgreSQL and is always quoted.
CREATE TABLE IF NOT EXISTS firmware_campaigns (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  package_id TEXT NOT NULL,
  group_id TEXT NOT NULL DEFAULT '',
  device_ids JSONB NOT NULL DEFAULT '[]',
  canary_count BIGINT NOT NULL DEFAULT 0,
  concurrency BIGINT NOT NULL DEFAULT 0,
  "window" JSONB,
  failure_threshold BIGINT NOT NULL DEFAULT 0,
  status TEXT NOT NULL,
  wave BIGINT NOT NULL DEFAULT 0,
  confirmed BOOLEAN NOT NULL DEFAULT FALSE,
  dry_run BOOLEAN NOT NULL DEFAULT FALSE,
  allow_downgrade BOOLEAN NOT NULL DEFAULT FALSE,
  verify_timeout_secs BIGINT NOT NULL DEFAULT 0,
  pause_reason TEXT NOT NULL DEFAULT '',
  job_id TEXT NOT NULL DEFAULT '',
  scheduled_at TIMESTAMPTZ,
  started_at TIMESTAMPTZ,
  finished_at TIMESTAMPTZ,
  created_by TEXT NOT NULL DEFAULT '',
  started_by TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  error TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS firmware_campaigns_status ON firmware_campaigns(status);
CREATE INDEX IF NOT EXISTS firmware_campaigns_package ON firmware_campaigns(package_id);

-- device_id is not a foreign key: the row is the update history. seq stands
-- in for SQLite's implicit rowid (insertion order within a wave).
CREATE TABLE IF NOT EXISTS firmware_campaign_devices (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  campaign_id TEXT NOT NULL REFERENCES firmware_campaigns(id) ON DELETE CASCADE,
  device_id TEXT NOT NULL,
  wave BIGINT NOT NULL DEFAULT 0,
  status TEXT NOT NULL,
  from_version TEXT NOT NULL DEFAULT '',
  to_version TEXT NOT NULL DEFAULT '',
  message TEXT NOT NULL DEFAULT '',
  started_at TIMESTAMPTZ,
  finished_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (campaign_id, device_id)
);
CREATE INDEX IF NOT EXISTS firmware_campaign_devices_device ON firmware_campaign_devices(device_id);
