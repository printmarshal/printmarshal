-- PostgreSQL schema: the same tables and columns as schema.sql with native
-- types (TEXT, BIGINT, DOUBLE PRECISION, BOOLEAN, TIMESTAMPTZ, JSONB, BYTEA).
-- Every statement is idempotent; OpenPostgres applies the files in name order
-- under an advisory lock and records the version in schema_migrations.

CREATE TABLE IF NOT EXISTS schema_migrations (version BIGINT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL);

CREATE TABLE IF NOT EXISTS devices (
  id TEXT PRIMARY KEY,
  address TEXT NOT NULL,
  hostname TEXT NOT NULL DEFAULT '',
  dns_name TEXT NOT NULL DEFAULT '',
  dns_name_suspect INTEGER NOT NULL DEFAULT 0,
  dns_checked_at TIMESTAMPTZ,
  mac TEXT NOT NULL DEFAULT '',
  serial TEXT NOT NULL DEFAULT '',
  uuid TEXT NOT NULL DEFAULT '',
  make TEXT NOT NULL DEFAULT '',
  model TEXT NOT NULL DEFAULT '',
  device_type TEXT NOT NULL DEFAULT '',
  firmware TEXT NOT NULL DEFAULT '',
  sys_descr TEXT NOT NULL DEFAULT '',
  sys_name TEXT NOT NULL DEFAULT '',
  enterprise_id BIGINT NOT NULL DEFAULT 0,
  admin_url TEXT NOT NULL DEFAULT '',
  capabilities JSONB NOT NULL DEFAULT '{}',
  discovery_methods JSONB NOT NULL DEFAULT '[]',
  identify_methods JSONB NOT NULL DEFAULT '[]',
  display_name TEXT NOT NULL DEFAULT '',
  display_name_source TEXT NOT NULL DEFAULT '',
  dns_sync INTEGER NOT NULL DEFAULT 0,
  location TEXT NOT NULL DEFAULT '',
  asset_tag TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  state TEXT NOT NULL DEFAULT 'discovered',
  status JSONB,
  supplies JSONB NOT NULL DEFAULT '[]',
  trays JSONB NOT NULL DEFAULT '[]',
  counters JSONB,
  severity TEXT NOT NULL DEFAULT 'ok',
  consecutive_failures BIGINT NOT NULL DEFAULT 0,
  first_seen TIMESTAMPTZ NOT NULL,
  last_seen TIMESTAMPTZ NOT NULL,
  last_polled TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS devices_serial ON devices(serial);
CREATE INDEX IF NOT EXISTS devices_uuid ON devices(uuid);
CREATE INDEX IF NOT EXISTS devices_mac ON devices(mac);
CREATE INDEX IF NOT EXISTS devices_address ON devices(address);
CREATE INDEX IF NOT EXISTS devices_state ON devices(state);
ALTER TABLE devices ADD COLUMN IF NOT EXISTS dns_name TEXT NOT NULL DEFAULT '';
ALTER TABLE devices ADD COLUMN IF NOT EXISTS dns_name_suspect INTEGER NOT NULL DEFAULT 0;
ALTER TABLE devices ADD COLUMN IF NOT EXISTS dns_checked_at TIMESTAMPTZ;
ALTER TABLE devices ADD COLUMN IF NOT EXISTS display_name_source TEXT NOT NULL DEFAULT '';
ALTER TABLE devices ADD COLUMN IF NOT EXISTS dns_sync INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS groups (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  description TEXT NOT NULL DEFAULT '',
  kind TEXT NOT NULL DEFAULT 'static',
  rule JSONB,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS group_members (
  group_id TEXT NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
  device_id TEXT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, device_id)
);

CREATE TABLE IF NOT EXISTS credentials (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  type TEXT NOT NULL,
  scope TEXT NOT NULL DEFAULT '',
  username TEXT NOT NULL DEFAULT '',
  priority BIGINT NOT NULL DEFAULT 0,
  purpose TEXT NOT NULL DEFAULT 'read',
  secret BYTEA NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

-- Migration 3 (audit A19) for databases created before the purpose column existed.
ALTER TABLE credentials ADD COLUMN IF NOT EXISTS purpose TEXT NOT NULL DEFAULT 'read';

CREATE TABLE IF NOT EXISTS jobs (
  id TEXT PRIMARY KEY,
  type TEXT NOT NULL,
  target JSONB NOT NULL DEFAULT '{}',
  params JSONB NOT NULL DEFAULT '{}',
  status TEXT NOT NULL,
  total BIGINT NOT NULL DEFAULT 0,
  done BIGINT NOT NULL DEFAULT 0,
  failed BIGINT NOT NULL DEFAULT 0,
  error TEXT NOT NULL DEFAULT '',
  created_by TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL,
  started_at TIMESTAMPTZ,
  finished_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS jobs_created ON jobs(created_at);

CREATE TABLE IF NOT EXISTS job_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id TEXT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  device_id TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL,
  message TEXT NOT NULL DEFAULT '',
  data JSONB,
  at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS job_results_job ON job_results(job_id);

CREATE TABLE IF NOT EXISTS telemetry (
  device_id TEXT NOT NULL,
  metric TEXT NOT NULL,
  label TEXT NOT NULL DEFAULT '',
  value DOUBLE PRECISION NOT NULL,
  at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS telemetry_lookup ON telemetry(device_id, metric, at);
CREATE INDEX IF NOT EXISTS telemetry_at ON telemetry(at);

CREATE TABLE IF NOT EXISTS alerts (
  id TEXT PRIMARY KEY,
  device_id TEXT NOT NULL,
  severity TEXT NOT NULL,
  source TEXT NOT NULL,
  key TEXT NOT NULL,
  description TEXT NOT NULL,
  raised_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  cleared_at TIMESTAMPTZ,
  acked_at TIMESTAMPTZ,
  acked_by TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS alerts_device ON alerts(device_id, key);
CREATE INDEX IF NOT EXISTS alerts_active ON alerts(cleared_at);

CREATE TABLE IF NOT EXISTS notification_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notifier TEXT NOT NULL,
  event TEXT NOT NULL,
  target TEXT NOT NULL DEFAULT '',
  ok BOOLEAN NOT NULL,
  error TEXT NOT NULL DEFAULT '',
  at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor TEXT NOT NULL,
  action TEXT NOT NULL,
  target TEXT NOT NULL DEFAULT '',
  before JSONB,
  after JSONB,
  result TEXT NOT NULL DEFAULT '',
  at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  external_issuer TEXT NOT NULL DEFAULT '',
  external_subject TEXT NOT NULL DEFAULT ''
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS external_issuer TEXT NOT NULL DEFAULT '';
ALTER TABLE users ADD COLUMN IF NOT EXISTS external_subject TEXT NOT NULL DEFAULT '';
ALTER TABLE devices ADD COLUMN IF NOT EXISTS web_url_probed TEXT NOT NULL DEFAULT '';
ALTER TABLE devices ADD COLUMN IF NOT EXISTS web_url_override TEXT NOT NULL DEFAULT '';
CREATE UNIQUE INDEX IF NOT EXISTS users_external ON users(external_issuer, external_subject) WHERE external_issuer <> '';

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS consumables (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'other',
  color TEXT NOT NULL DEFAULT '',
  part_number TEXT NOT NULL DEFAULT '',
  compatible_models JSONB NOT NULL DEFAULT '[]',
  unit TEXT NOT NULL DEFAULT 'each',
  on_hand BIGINT NOT NULL DEFAULT 0,
  warning_at BIGINT NOT NULL DEFAULT 0,
  critical_at BIGINT NOT NULL DEFAULT 0,
  location TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  reorder_url TEXT NOT NULL DEFAULT '',
  unit_cost DOUBLE PRECISION,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS consumables_part ON consumables(part_number);
CREATE INDEX IF NOT EXISTS consumables_type ON consumables(type, color);

CREATE TABLE IF NOT EXISTS consumable_stock_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consumable_id TEXT NOT NULL REFERENCES consumables(id) ON DELETE CASCADE,
  actor TEXT NOT NULL DEFAULT '',
  kind TEXT NOT NULL,
  delta BIGINT NOT NULL DEFAULT 0,
  resulting BIGINT NOT NULL DEFAULT 0,
  reason TEXT NOT NULL DEFAULT '',
  device_id TEXT NOT NULL DEFAULT '',
  supply_index BIGINT NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'applied',
  at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS stock_events_item ON consumable_stock_events(consumable_id, at);
CREATE INDEX IF NOT EXISTS stock_events_status ON consumable_stock_events(status);

CREATE TABLE IF NOT EXISTS supply_links (
  device_id TEXT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
  supply_index BIGINT NOT NULL,
  consumable_id TEXT NOT NULL REFERENCES consumables(id) ON DELETE CASCADE,
  source TEXT NOT NULL DEFAULT 'auto',
  updated_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (device_id, supply_index)
);
CREATE INDEX IF NOT EXISTS supply_links_item ON supply_links(consumable_id);

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value JSONB NOT NULL
);
